"""Shared utilities for normalising media URLs returned by S3/MinIO storage.

S3Boto3Storage with MinIO produces absolute URLs such as
``http://localhost/anishows-media/media/avatars/pic.jpg``.  These bypass the
Caddy reverse-proxy that fronts MinIO via ``/media/*``, causing *Access Denied*
errors.  Every code path that surfaces a media URL to the frontend must pass
the raw value through :func:`normalize_media_url` so it becomes a Caddy-safe
relative path like ``/media/avatars/pic.jpg``.
"""

import re
from urllib.parse import urlparse

from .logger import logger

# Hosts that indicate the URL was generated by the internal S3/MinIO storage
# and should be rewritten to a relative ``/media/…`` path.
_INTERNAL_HOSTS = frozenset({"localhost", "127.0.0.1", "minio", "web"})

# Matches path-style bucket URLs: ``/<bucket>/media/…``
_BUCKET_PREFIX_RE = re.compile(r"^/[^/]+/media/")


def normalize_media_url(url: str | None) -> str | None:
    """Normalise an S3/MinIO media URL to a Caddy-safe relative path.

    * Internal hosts (localhost, minio, …) → strip scheme+host, keep ``/media/…``
    * Path-style bucket prefixes (``/<bucket>/media/…``) → ``/media/…``
    * External URLs (``https://…``) → returned unchanged
    * ``None`` / empty → ``None``
    """
    if not url:
        return None

    if url.startswith(("http://", "https://")):
        parsed = urlparse(url)
        host = (parsed.hostname or "").lower()
        if host in _INTERNAL_HOSTS:
            media_idx = parsed.path.find("/media/")
            url = parsed.path[media_idx:] if media_idx != -1 else parsed.path
        else:
            return url

    if isinstance(url, str) and _BUCKET_PREFIX_RE.match(url):
        url = _BUCKET_PREFIX_RE.sub("/media/", url, count=1)

    return url or None


def field_media_url(field) -> str | None:
    """Return the normalised URL of a file or image field, or ``None``.

    Reading ``field.url`` asks the storage backend (and, for ImageKit specs, the
    cache-file namer) for a URL. That fails in backend-specific ways: a missing
    source, S3 signing or credentials, a misconfigured storage. Every caller
    only wants "a URL or nothing" so that a broken image never breaks a payload,
    which is why any error here means "no URL".
    """
    # An empty ImageKit spec file is falsy but its .url is the bare MEDIA_URL.
    if not field:
        return None
    try:
        url = field.url
    except Exception:
        logger.debug("Could not resolve a media URL", exc_info=True)
        return None
    return normalize_media_url(url)
